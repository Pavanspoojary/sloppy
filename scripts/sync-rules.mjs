#!/usr/bin/env node
/**
 * Generates the human-readable rule tables from CANONICAL_RULES so the README,
 * docs/RULES.md, and the catalog can never assign two meanings to one ID.
 *
 * Run: npm run rules:sync
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');
let drift = 0;
const writeIfChanged = (file, content) => {
  let current = '';
  try { current = fs.readFileSync(file, 'utf8'); } catch {}
  if (current === content) return;
  if (CHECK_ONLY) {
    drift++;
    console.error(`Rule table drift: ${path.relative(ROOT, file)} is out of date. Run npm run rules:sync.`);
    return;
  }
  fs.writeFileSync(file, content);
};
const { CANONICAL_RULES, AUTO_FIX_RULE_TYPES, RULE_METADATA } = await import(path.join(ROOT, 'packages/core/dist/index.js'));

const rules = Object.entries(CANONICAL_RULES)
  .map(([slug, rule]) => ({ slug, ...rule }))
  .sort((a, b) => a.ruleId.localeCompare(b.ruleId, 'en', { numeric: true }));

const descriptionFor = (slug) => {
  const text = {
    HERO_GRADIENT_TEXT: 'Gradient text clipped to a transparent heading fill.',
    PURPLE_GRADIENT_SLOP: 'Purple, indigo, or violet gradients used as a default accent.',
    EMERALD_MONOCULTURE: 'Gen-2 emerald-on-dark accents with no declared brand token.',
    BLUR_OVERUSE: 'Backdrop blur used as the default surface instead of a rare overlay.',
    GLOW_SHADOW: 'Colored ambient glow shadows around cards or controls.',
    LOW_CONTRAST_GRAY: 'Body or label text below WCAG AA contrast.',
    SPARKLE_ICON_OVERLOAD: 'Decorative sparkle or magic-wand icons on generic actions.',
    FABRICATED_SOCIAL_PROOF: 'Invented metrics, logos, or testimonials.',
    STATUS_DOT_SLOP: 'Pulsing green status dot with no health endpoint behind it.',
    AI_PROSE_FILLER: 'Em-dash chains, adjective triplets, false ranges, and vague attribution.',
    DEAD_PLACEHOLDER_SLOP: 'Dead anchors or empty click handlers.',
    SCROLL_HIJACKING: 'Global scroll locks or wheel interception.',
    FAKE_CONTROL_SLOP: 'Clickable div or span without role or keyboard access.',
    NON_NULL_ASSERTION_SLOP: 'Chained non-null assertions bypassing null checks.',
    AI_NARRATION_COMMENT_SLOP: 'Line-by-line narration comments and divider banners.',
    DESIGN_TOKEN_DRIFT: 'A hard-coded color outside the palette locked in DESIGN.md.',
    UNBOUNDED_INFINITE_MOTION: 'Infinite programmatic repeat/loop animations without a progress or spinner context.',
    REDUCED_MOTION_BLINDNESS: 'Active runtime motion, scroll, 3D, or Lottie code missing a prefers-reduced-motion guard.',
    LAYOUT_THRASH_ANIMATION: 'Programmatic animation of layout geometry (width, height, top, left, margin, padding).',
    UNMANAGED_WEBGL_OR_MEDIA_LOOP: 'Uncleaned WebGL, Lottie, or scroll instances and unbounded R3F Canvas render loops.',
    TRANSITION_ALL_SLOP: '`transition: all` / `transition-all` animating unknown properties.',
    SLOW_INTERACTION_MOTION: 'Hover, press, or focus feedback slower than ~600ms.',
    SCROLL_REVEAL_SATURATION: 'Every section revealed on scroll and hidden until JavaScript runs.',
    AUTOPLAY_MOTION_WITHOUT_CONTROL: 'Marquee, ticker, carousel, or video that runs automatically with no pause control.',
    FLASHING_ANIMATION: 'Blink, flash, or strobe animation above the three-per-second limit.',
    SCALE_FROM_ZERO: 'An entrance that starts at scale(0) and reads as a pop-in.',
    CSS_LOOP_NO_REDUCED_GUARD: 'Looping CSS animation with no prefers-reduced-motion fallback.',
    VESTIBULAR_RISK_MOTION: 'Full-area parallax, fixed backgrounds, and 3D hover tilt.',
    UNEARNED_HOVER_LIFT: 'Hover lift or scale on a surface that is not clickable.',
    OFF_CONTRACT_MOTION: 'A duration beyond the motion scale declared in DESIGN.md.',
    UNIFORM_ENTRANCE_MOTION: 'One identical fade-up on four or more blocks, or mount motion on headings, paragraphs, and navigation.',
    ELASTIC_UI_EASING: 'Overshoot or elastic cubic-bezier easing on routine surfaces instead of ease-out.',
    WILL_CHANGE_LEAK: 'will-change declared across several elements and left on permanently.'
  }[slug];
  return text || CANONICAL_RULES[slug].title;
};

const header = '| ID | Slug | Title | Tier | Severity | Mode | Confidence | Kind | What it catches |\n| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |';
const rows = rules.map((rule) => {
  const meta = RULE_METADATA[rule.slug] || {};
  return `| \`${rule.ruleId}\` | \`${rule.slug}\` | ${rule.title} | ${rule.tier} | ${rule.defaultSeverity} | ${rule.mode} | ${meta.confidence || '-'} | ${meta.objective ? 'objective' : 'craft'} | ${descriptionFor(rule.slug)} |`;
});

const block = `<!-- RULES:START (generated by scripts/sync-rules.mjs; do not edit by hand) -->\n${header}\n${rows.join('\n')}\n<!-- RULES:END -->`;

const rulesDoc = `# Canonical Rule Table

Generated from \`CANONICAL_RULES\` in \`packages/core/src/linter/types.ts\` by
\`npm run rules:sync\`. The README table and the catalog title cells are generated
from the same table, so an ID has exactly one meaning everywhere.

- **Tier** is the enforcement gate: \`floor\` blocks, \`reflex\` needs a written rationale or cleanup, \`finish\` is advisory.
- **Mode** is honest about capability: \`auto-fix\` means \`sloppy fix\` rewrites it; \`detect-only\` means a human or agent must decide.
- **Slug and ID are interchangeable** in \`sloppy-ignore\`, \`sloppy.config.json\`, and \`sloppy fix --only\`.

${block}

## Auto-fix coverage

${AUTO_FIX_RULE_TYPES.map((type) => `- \`${CANONICAL_RULES[type].ruleId}\` \`${type}\``).join('\n')}

Everything else is **detect-only** on purpose: swapping a brand accent, rewriting
copy, or changing layout framing is a design decision, not a mechanical rewrite.

## Evidence & false-positive controls

Each rule declares the evidence it actually collects, how confident the detector
is, whether the finding is objective or a craft judgment, and when it must stay
quiet. \`sloppy rules --json\` exposes the same fields to agents.

${rules.map((rule) => {
  const meta = RULE_METADATA[rule.slug] || {};
  const evidence = (meta.evidenceKinds || ['source']).join(', ');
  return `### \`${rule.ruleId}\` ${rule.title}
- **Family**: ${meta.family || 'unknown'}
- **Confidence**: ${meta.confidence || 'medium'} (${meta.objective ? 'objective defect' : 'craft judgment'})
- **Evidence collected**: ${evidence}
- **False positives**: ${(meta.falsePositives || []).join(' ') || 'None documented.'}
- **Not applicable when**: ${(meta.notApplicableWhen || []).join(' ') || 'None documented.'}
- **Validation**: ${(meta.validation || []).join(' ') || 'Review the finding manually.'}${meta.autoFixScope ? `\n- **Auto-fix scope**: ${meta.autoFixScope}` : ''}${meta.sourceUrls?.length ? `\n- **Sources**: ${meta.sourceUrls.join(', ')}` : ''}`;
}).join('\n\n')}
`;

writeIfChanged(path.join(ROOT, 'docs/RULES.md'), `${rulesDoc.trimEnd()}\n`);

const README_PATH = path.join(ROOT, 'README.md');
let readme = fs.readFileSync(README_PATH, 'utf8');
const startMarker = '<!-- RULES:START';
const endMarker = '<!-- RULES:END -->';
if (readme.includes(startMarker) && readme.includes(endMarker)) {
  const start = readme.indexOf(startMarker);
  const end = readme.indexOf(endMarker) + endMarker.length;
  readme = `${readme.slice(0, start)}${block}${readme.slice(end)}`;
} else {
  const tableStart = readme.indexOf('| Rule ID | Canonical Slug |');
  if (tableStart < 0) throw new Error('README is missing its rule table and RULES markers');
  const tableEnd = readme.indexOf('\n\n', tableStart);
  if (tableEnd < 0) throw new Error('README rule table has no terminator');
  readme = `${readme.slice(0, tableStart)}${block}${readme.slice(tableEnd)}`;
}
writeIfChanged(README_PATH, readme);

// Align the catalog's title cell for every implemented rule. Catalog-only rows
// (rules not yet enforced by the scanner) are left untouched.
const CATALOG_PATH = path.join(ROOT, 'docs/AI_SLOP_CATALOG.md');
const byId = new Map(rules.map((rule) => [rule.ruleId, rule]));
const catalog = fs.readFileSync(CATALOG_PATH, 'utf8').split('\n').map((line) => {
  const match = line.match(/^\| `([A-Z]+-\d+)` \| \*\*(.+?)\*\* \|/);
  if (!match) return line;
  const rule = byId.get(match[1]);
  if (!rule) return line;
  return line.replace(`**${match[2]}**`, `**${rule.title}**`);
});
writeIfChanged(CATALOG_PATH, catalog.join('\n'));

if (CHECK_ONLY) {
  if (drift) process.exitCode = 1;
  else console.log(`Rule tables are in sync (${rules.length} canonical rules).`);
} else {
  console.log(`Synced ${rules.length} canonical rules to docs/RULES.md, README.md, and docs/AI_SLOP_CATALOG.md`);
}
